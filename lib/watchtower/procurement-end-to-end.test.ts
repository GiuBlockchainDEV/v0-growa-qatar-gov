import {describe,it,expect} from 'vitest'
import {readFileSync} from 'node:fs'
import {join} from 'node:path'
const read=(name:string)=>readFileSync(join(process.cwd(),name),'utf8')
const mission=read('components/dashboard/watchtower/procurement-mission.tsx')
const map=read('components/dashboard/watchtower/procurement-route-desk.tsx')
const onboarding=read('components/dashboard/watchtower/procurement-qualification-desk.tsx')
const paths=read('lib/watchtower/procurement-route-evidence.ts')
const css=read('components/dashboard/watchtower/procurement-mission.module.css')
describe('Procurement end-to-end agentic workbench',()=>{
 it('keeps real provider mapRoutes and route evidence; no fake sea lines',()=>{
  expect(mission).toContain('corridors[country]=response.value.payload')
  expect(mission).toContain('Array.isArray(result.mapRoutes)')
  expect(mission).toContain('<ProcurementRouteDesk')
  expect(map).toContain('LogisticsRouteMap')
  expect(map).toContain('mapRouteEvidence')
  expect(map).toContain('orderRouteAlternatives')
  expect(map).toContain('routePassages')
  expect(map).toContain('Lower risk index first')
  expect(map).toContain('Shortest theoretical ETA first')
  expect(map).toContain('Lower estimated freight first')
  expect(paths).toContain('No guessed sea lines')
  expect(css).toContain('.routeMap{')
 })
 it('blocks strategy finalization pending route evidence approval',()=>{
  expect(mission).toContain('logisticsApprovals.length')
  expect(mission).toContain('Review geographic routes, risks and pass-through steps')
  expect(map).toContain('Approve selected logistics alternative')
  expect(map).toContain('preferredCorridor(all)')
 })
 it('covers real supplier onboarding, contractual review and official order status',()=>{
  expect(mission).toContain('<ProcurementQualificationDesk')
  expect(mission).toContain('Purchase order decision file')
  expect(mission).toContain("kind:'purchase_order'")
  expect(onboarding).toContain("create('supplier'")
  expect(onboarding).toContain("create('contract'")
  expect(onboarding).toContain("kind:'approval'")
  expect(onboarding).toContain("action:decision")
  expect(onboarding).toContain('Approved contractual capacity')
  expect(onboarding).toContain('Create supplier · Pending approval')
  expect(onboarding).toContain('Create contract · Pending approval')
  expect(onboarding).toContain('A proposer cannot approve their own supplier.')
 })
 it('preserves separation of preliminary sourcing and legally binding orders',()=>{
  expect(mission).toContain('NO BINDING QUOTE')
  expect(mission).toContain('NOT a legally placed order')
  expect(onboarding).toContain('not merely a search listing')
  expect(map).toContain('not scheduled flights')
  expect(map).toContain('not freight booking')
 })
})
