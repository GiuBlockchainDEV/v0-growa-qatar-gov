import {describe,expect,it} from 'vitest'
import {readFileSync} from 'node:fs'
import {join} from 'node:path'
const source=(path:string)=>readFileSync(join(process.cwd(),path),'utf8')
const nav=source('components/dashboard/watchtower-workspace.tsx')
const room=source('components/dashboard/watchtower/agent-operations-room.tsx')
const lab=source('components/dashboard/commodity-agent-lab.tsx')
const css=source('components/dashboard/watchtower/agent-operations-room.module.css')
describe('Watchtower agent operations flow-first UI',()=>{
 it('keeps the retired Scenario Room removed and redirects older hash links',()=>{
  expect(nav).not.toContain('WatchtowerScenarioRoom')
  expect(nav).not.toContain("id: 'scenarios'")
  expect(nav).toContain("hash === '#watchtower-scenarios') setActiveSection('agents')")
 })
 it('shows setup, analysis and a single decision in the correct order',()=>{
  expect(room).toContain('Define the mission')
  expect(room).toContain('Specialist analysis')
  expect(room).toContain('Decision & next action')
  expect(room.indexOf('Define the mission')).toBeLessThan(room.indexOf('Specialist analysis'))
  expect(room.indexOf('Specialist analysis')).toBeLessThan(room.indexOf('Decision & next action'))
  expect(room).toContain("const workstreams=[")
  expect(room).toContain("steps:['orchestrate','quality','food']")
  expect(room).toContain("steps:['agronomy','procurement','logistics','reserves']")
  expect(room).toContain("steps:['weather','watchtower']")
 })
 it('does not duplicate the simulator configuration or final review',()=>{
  expect(room).toContain('<CommodityAgentLab key={commodityId')
  expect(room).toContain('mode="watchtower"')
  expect(lab).toContain("mode?:'standard'|'watchtower'")
  expect(lab).toContain('Fine-tune shock assumptions')
  expect(lab).toContain('Inspect detailed agent evidence, charts and simulated reviewer actions')
  expect(lab).toContain("inWatchtower ? (result ? (")
  expect(lab).toContain("!inWatchtower&&workflowComplete")
 })
 it('does not claim results before the real user-run simulation ends',()=>{
  expect(lab).toContain('verdict:workflowComplete?recommendation:null')
  expect(lab).toContain('steps:result?result.steps.slice(0,revealed):[]')
  expect(lab).toContain('const [session,setSession]=useState<AgentRunSession|null>(null)')
  expect(room).toContain("const finished=telemetry.phase==='completed'&&telemetry.verdict!==null")
  expect(room).toContain("const verdict=finished?telemetry.verdict:null")
 })
 it('uses reviewed evidence and keeps execution under human control',()=>{
  expect(room).toContain('useCommodityCase(commodityId,days)')
  expect(room).toContain('linkCommodityOperations(commodityId,operations,today)')
  expect(room).toContain('No live LLM agent execution')
  expect(room).not.toContain("method: 'POST'")
  expect(lab).not.toContain("method: 'POST'")
  expect(css).toContain('.flowStreams')
  expect(css).toContain('prefers-reduced-motion')
 })
})
