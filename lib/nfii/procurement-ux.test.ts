import {readFileSync} from 'node:fs'
import {join} from 'node:path'
import {describe,expect,it} from 'vitest'
const read=(p:string)=>readFileSync(join(process.cwd(),p),'utf8')
const workspace=read('components/dashboard/nfii-ops/operations-workspace.tsx')
const journey=read('components/dashboard/nfii-ops/procurement-journey.tsx')
const discovery=read('components/dashboard/nfii-ops/global-supplier-research.tsx')

describe('Guided procurement experience',()=>{
  it('opens a clear overview instead of mixing every feature into one screen',()=>{
    expect(workspace).toContain("useState<ProcurementTab>('overview')")
    expect(workspace).toContain('<ProcurementJourney')
    expect(workspace).toContain('<ProcurementHome')
    expect(workspace).toContain("procurementTab==='overview'")
    expect(workspace).toContain("procurementTab==='discover'?null")
    expect(journey).toContain('Your procurement journey')
    expect(journey).toContain('From supplier discovery to approved purchase')
    expect(journey).toContain('Suggested next step')
    expect(journey).toContain('What counts as approved?')
  })
  it('separates research, suppliers, contracts, orders and approvals',()=>{
    for(const step of ["'discover'","'suppliers'","'contracts'","'orders'","'approvals'"])
      expect(journey).toContain(step)
    expect(workspace).toContain("focus==='procurement'&&procurementTab==='discover'")
    expect(workspace).toContain('<ProcurementStageHeading tab={procurementTab}/>')
    expect(workspace).toContain("focus!=='procurement'||procurementTab!=='approvals'")
    expect(workspace).toContain("focus!=='procurement'||procurementTab==='approvals'")
    expect(discovery).toContain('Global supplier research')
    expect(discovery).toContain('Discovery ≠ qualification')
  })
  it('maps each task to a single creation form without changing server authorization',()=>{
    expect(workspace).toContain('procurementTabCollection(tab)')
    expect(workspace).toContain('procurementTabKind(tab)')
    expect(workspace).toContain("focus!=='procurement' && <label")
    expect(workspace).toContain("formKind==='supplier'")
    expect(workspace).toContain("formKind==='contract'")
    expect(workspace).toContain("formKind==='purchase_order'")
    expect(workspace).toContain("missingProcurementParent")
    expect(workspace).toContain('An approved supplier is required')
    expect(workspace).toContain('An approved, currently valid contract is required')
    expect(workspace).toContain('Your account does not have permission')
    expect(workspace).toContain("if(!orgId||busy||!canCreate||isPreview)return")
    expect(workspace).toContain("method:'POST'")
    expect(workspace).toContain("user?.id!==row.submitted_by")
  })
  it('keeps an empty authorized ledger in live mode without synthetic records',()=>{
    expect(workspace).toContain('const isPreview=!orgId||snapshot===null')
    expect(workspace).not.toContain('previewOperationsSnapshot(today)')
    expect(workspace).not.toContain('setForcePreview(true)')
    expect(workspace).toContain('Organization register is empty. Add an actual supplier to begin.')
    expect(workspace).toContain("canEdit=!isPreview")
  })
  it('keeps the Logistics register and separate Reserves command with audit controls',()=>{
    expect(workspace).toContain("focus==='logistics' && <div")
    expect(workspace).toContain("<StrategicReservesCommand")
    expect(workspace).toContain("focus!=='procurement'&&<section")
    expect(workspace).toContain('Immutable operation events')
    expect(workspace).toContain('Confirm & audit')
  })
})
