import {readFileSync} from 'node:fs'
import {join} from 'node:path'
import {describe,expect,it} from 'vitest'
const read=(path:string)=>readFileSync(join(process.cwd(),path),'utf8')
const route=read('app/api/nfii/procurement/discovery/route.ts')
const helpers=read('lib/nfii/procurement-global.ts')
const screen=read('components/dashboard/nfii-ops/global-supplier-research.tsx')
const workspace=read('components/dashboard/nfii-ops/operations-workspace.tsx')

describe('NFII global procurement source and permission boundaries',()=>{
  it('permits only authenticated, scoped external source read requests',()=>{
    expect(route).toContain("supabase.auth.getUser()")
    expect(route).toContain("requireCapability('supply.view',org)")
    expect(route).toContain("if(org&&!validFoodUuid(org))")
    expect(route).toContain("if(provider==='places')")
    expect(route).toContain("if(!org)return reply")
    expect(route).toContain("process.env.GOOGLE_PLACES_API_KEY")
    expect(route).not.toContain('NEXT_PUBLIC_GOOGLE')
    expect(route).toContain("provider:'comtrade'")
    expect(route).toContain("provider:'gleif'")
    expect(route).not.toContain('createAdminClient')
    expect(route).not.toMatch(/\.insert\(|\.upsert\(|\.update\(/)
  })
  it('keeps remote hosts allowlisted and never trusts external links or vendor qualifications',()=>{
    expect(helpers).toContain('https://api.gleif.org/api/v1/lei-records')
    expect(helpers).toContain('https://comtradeapi.un.org/public/v1/preview/C/A/HS')
    expect(route).toContain('https://places.googleapis.com/v1/places:searchText')
    expect(route).toContain("cache:'no-store'")
    expect(route).toContain("ttl")
    expect(helpers).toContain("supplierQualification:'not_assessed'")
    expect(helpers).toContain("candidate.protocol==='https:'")
    expect(helpers).toContain('function supplierDraftCode')
    expect(route).toContain('No results were fabricated')
  })
  it('shows 3 sourcing research modes and keeps saving in the existing procurement workflow',()=>{
    expect(screen).toContain("key:'gleif'")
    expect(screen).toContain("key:'places'")
    expect(screen).toContain("key:'comtrade'")
    expect(screen).toContain('Global supplier research')
    expect(screen).toContain('Discovery ≠ qualification')
    expect(screen).toContain('Prepare supplier draft')
    expect(screen).toContain('supplier register')
    expect(workspace).toContain('<GlobalSupplierResearch')
    expect(workspace).toContain("focus==='procurement'")
    expect(workspace).toContain("candidate.source!=='GLEIF'")
    expect(workspace).toContain("setFormKind('supplier')")
    expect(workspace).toContain("setFormOpen(true)")
    expect(workspace).toContain("Save for independent review")
    expect(workspace).toContain("if(!orgId||busy||!canCreate||isPreview)return")
    expect(screen).not.toContain("method:'POST'")
  })
  it('does not make trade countries into named or approved suppliers',()=>{
    expect(helpers).toContain("reporter:'Qatar'")
    expect(helpers).toContain("partnerCode:partner")
    expect(helpers).toContain("tradeValueUsd")
    expect(helpers).toContain("HS_CODES")
    expect(screen).toContain('National country statistics, not supplier-level transactions')
    expect(screen).toContain('No company or country data has been replaced with fabricated values')
    expect(screen).toContain("row.source!=='GLEIF'")
  })
})
